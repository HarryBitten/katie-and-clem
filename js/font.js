function textWidth(s, sc = 1) {
  let w = 0;
  for (const ch of s) w += ((ch === ' ') ? 3 : (FONT[ch] ? FONT[ch].w + 1 : 4));
  return Math.max(0, w - 1) * sc;
}
function drawText(g, s, x, y, col, sc = 1) {
  g.fillStyle = col;
  let cx = x;
  for (const ch of s) {
    if (ch === ' ') { cx += 3 * sc; continue; }
    const gl = FONT[ch]; if (!gl) { cx += 4 * sc; continue; }
    for (let r = 0; r < gl.rows.length; r++) {
      const row = gl.rows[r];
      for (let c = 0; c < row.length; c++) if (row[c] === '#') g.fillRect(cx + c * sc, y + r * sc, sc, sc);
    }
    cx += (gl.w + 1) * sc;
  }
  return cx;
}
function wrapText(s, maxW, sc = 1) {
  const words = s.split(' '), lines = []; let cur = '';
  for (const w of words) {
    const t = cur ? cur + ' ' + w : w;
    if (textWidth(t, sc) > maxW && cur) { lines.push(cur); cur = w; } else cur = t;
  }
  if (cur) lines.push(cur);
  return lines;
}
